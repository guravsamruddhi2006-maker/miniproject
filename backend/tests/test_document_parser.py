import os
import tempfile
import pytest
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from app.services.document_parser import (
    validate_pdf_file,
    _parse_financial_number,
    extract_metrics_from_document,
)

def test_validate_pdf_file():
    valid_pdf_bytes = b"%PDF-1.4\n1 0 obj\n<<>>\nendobj"
    is_valid, err = validate_pdf_file(valid_pdf_bytes, "report.pdf")
    assert is_valid is True
    assert err is None

    invalid_bytes = b"NOT_A_PDF_DOCUMENT_CONTENT"
    is_valid, err = validate_pdf_file(invalid_bytes, "fake.pdf")
    assert is_valid is False
    assert "Invalid document" in err

    oversized_bytes = b"%PDF-" + b"0" * (51 * 1024 * 1024)
    is_valid, err = validate_pdf_file(oversized_bytes, "huge.pdf")
    assert is_valid is False
    assert "exceeds maximum allowed limit" in err

def test_parse_financial_numbers():
    assert _parse_financial_number("$383,285") == 383285.0
    assert _parse_financial_number("(96,995)") == -96995.0
    assert _parse_financial_number("6.13") == 6.13
    assert _parse_financial_number("-12,345.67") == -12345.67
    assert _parse_financial_number("NotANumber") is None

def test_extract_metrics_from_generated_pdf():
    # Create temporary PDF with standard corporate 10-K lines
    with tempfile.NamedTemporaryFile(suffix=".pdf", delete=False) as tmp:
        tmp_path = tmp.name

    try:
        c = canvas.Canvas(tmp_path, pagesize=letter)
        c.drawString(100, 750, "Apple Inc. Form 10-K Annual Report (Consolidated)")
        c.drawString(100, 720, "Total net sales: $383,285")
        c.drawString(100, 700, "Gross profit: $169,148")
        c.drawString(100, 680, "Operating income: $114,301")
        c.drawString(100, 660, "Net income: $96,995")
        c.drawString(100, 640, "Total assets: $352,583")
        c.drawString(100, 620, "Total liabilities: $290,437")
        c.drawString(100, 600, "Cash generated by operating activities: $110,543")
        c.drawString(100, 580, "Earnings per share - diluted: $6.13")
        c.showPage()
        c.save()

        metrics = extract_metrics_from_document(tmp_path)
        assert len(metrics) == 8
        metrics_by_name = {m["name"]: m for m in metrics}

        assert metrics_by_name["Total Revenue"]["value"] == 383285000000.0
        assert metrics_by_name["Net Income"]["value"] == 96995000000.0
        assert metrics_by_name["Diluted EPS"]["value"] == 6.13
        assert "Page 1" in metrics_by_name["Total Revenue"]["source_snippet"]
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
